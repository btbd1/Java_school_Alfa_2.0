import java.util.Random;


public class Main {

  public static void main(String[] args) {

//    примеры диапазонов при генерации с помощью Random
    Random random = new Random();

// 1. Случайное целое без ограничения диапазона
    int a = random.nextInt();
// Комментарий: возвращает значение в диапазоне
// [Integer.MIN_VALUE, Integer.MAX_VALUE] (от –2 147 483 648 до 2 147 483 647).

// 2. Случайное целое в диапазоне [0, 99]
    int b = random.nextInt(100);
// Комментарий: возвращает значение от 0 (включительно) до 100 (исключительно), т.е. 0‑99.

// 3. Случайное целое в диапазоне [5, 100]
    int c = random.nextInt(100 - 5 + 1) + 5;
// Комментарий: выражение (100‑5+1) даёт 96, поэтому nextInt(96) генерирует
// числа от 0 до 95, а прибавление 5 смещает диапазон к 5‑100 (включительно).

// 4. Случайное вещественное число в диапазоне [0.0, 1.0)
    double d = random.nextDouble();
// Комментарий: возвращает значение от 0.0 (включительно) до 1.0 (исключительно).

// 5. Случайное вещественное число в диапазоне [0.0, 10.0)
    double e = 10.0 * random.nextDouble();
// Комментарий: умножение масштабирует диапазон до 0.0 ≤ e < 10.0
// (10.0 не включается).

// 6. Случайное вещественное число в диапазоне [2.0, 10.0)
    double f = 2.0 + (10.0 - 2.0) * random.nextDouble();
// Комментарий: (10.0‑2.0) = 8.0, поэтому получаем 2.0 ≤ f < 10.0
// (верхняя граница 10.0 не включается).
  }
}